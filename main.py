#!/usr/bin/env python3
"""make.fun entry: Sum up 25 November's world news in one image.

Writes one image to /output/entry.png.

The brief allows the simplest program: it copies an image the repository
holds. The image (entry.png, 1024x1024, generated by generate_image.py
from news.json) is the one-page summary of Wednesday 25 November 2026
world news. This program is stdlib-only, uses no network, and is fully
deterministic: every run writes the exact same bytes.

Usage: python3 main.py
"""
import hashlib
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "entry.png")
EXPECTED_SHA256 = "09b7d977b86aa9e03dcc2d90e64c5cbe1f7e25603ab9a5be87d955e502ee846a"


def output_path():
    """Preferred /output/entry.png; fall back to ./output/entry.png."""
    preferred = os.path.join(os.sep, "output", "entry.png")
    try:
        os.makedirs(os.path.dirname(preferred), exist_ok=True)
        return preferred
    except OSError:
        local = os.path.join(HERE, "output", "entry.png")
        os.makedirs(os.path.dirname(local), exist_ok=True)
        return local


def main():
    if not os.path.exists(SOURCE):
        print("entry.png missing next to main.py", file=sys.stderr)
        return 1
    dest = output_path()
    shutil.copyfile(SOURCE, dest)
    digest = hashlib.sha256(open(dest, "rb").read()).hexdigest()
    if digest != EXPECTED_SHA256:
        print(f"SHA256 MISMATCH: {digest} != {EXPECTED_SHA256}",
              file=sys.stderr)
        return 1
    size = os.path.getsize(dest)
    print(f"wrote {dest} ({size} bytes, sha256 {digest[:16]}...)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
